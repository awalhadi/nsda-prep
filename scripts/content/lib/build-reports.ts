// Markdown reports written by content:build (deterministic; no timestamps).

import type { BuildResult, ConceptResult, Erratum } from "./build-core.ts";
import type { Issue } from "./checks.ts";
import type { Evidence, EvQuestion } from "./evidence.ts";

const esc = (s: string) => s.replace(/\|/g, "\\|").replace(/\n+/g, " / ");
const cut = (s: string, n: number) => (s.length > n ? s.slice(0, n - 1) + "…" : s);
const starStr = (n: number) => "★".repeat(n) + "☆".repeat(3 - n);

function pdfLink(ev: Evidence, src: string, page: number): string {
  const file = ev.sources.get(src)?.file;
  return file ? `[${src} p.${page}](../${encodeURI(file)}#page=${page})` : `${src} p.${page}`;
}

export function renderCoverage(
  coverage: BuildResult["coverage"],
  ev: Evidence,
  results: ConceptResult[],
  unmapped: Record<string, string>,
  linkedQuestions: string[] = [],
): string {
  const out: string[] = ["# Coverage Report", "", "> Generated by `npm run content:build`. Do not edit by hand.", ""];
  const total = coverage.reduce((s, c) => s + c.total, 0);
  const covered = coverage.reduce((s, c) => s + c.covered, 0);
  out.push(`**${covered} of ${total}** highlight passages are covered by a concept (**${total - covered} uncovered**). Every highlight annotation (1,409 total) belongs to one of these passages.`, "");
  out.push("| CBLM | Passages | Covered | Uncovered | Concepts |", "|---|---|---|---|---|");
  for (const c of coverage) {
    const concepts = results.filter((r) => r.concept?.cblmPrimary === c.cblm).length;
    out.push(`| ${c.cblm} | ${c.total} | ${c.covered} | ${c.total - c.covered} | ${concepts} |`);
  }
  out.push("", "CBLM 4 (Apply ICT to facilitate in training and assessment) has no PDF, so it has no highlights.", "");

  const mapped = new Set([...results.flatMap((r) => r.concept?.questions ?? []), ...linkedQuestions]);
  const bySrc = new Map<string, { total: number; mapped: number }>();
  for (const [id, q] of ev.questions) {
    const s = bySrc.get(q.src) ?? { total: 0, mapped: 0 };
    s.total++;
    if (mapped.has(id) || unmapped[id]) s.mapped++;
    bySrc.set(q.src, s);
  }
  out.push("## Questions mapped to concepts", "", "| Source | Questions | Mapped |", "|---|---|---|");
  for (const [src, s] of [...bySrc].sort()) out.push(`| ${src} | ${s.total} | ${s.mapped} |`);
  out.push("");

  for (const c of coverage.filter((x) => x.covered > 0 && x.uncovered.length)) {
    out.push(`## Uncovered passages in CBLM ${c.cblm}`, "");
    for (const id of c.uncovered) {
      const p = ev.passages.get(id)!;
      out.push(`- \`${id}\` (${pdfLink(ev, p.src, p.page)}): ${esc(cut(p.text, 110))}`);
    }
    out.push("");
  }
  return out.join("\n");
}

function issueRows(issues: { id: string; issue: Issue }[]): string[] {
  return issues.map(({ id, issue }) => `- \`${id}\` · \`${issue.path}\` · **${issue.code}**: ${esc(issue.message)}`);
}

export function renderReviewQueue(results: ConceptResult[], global: Issue[], errata: Erratum[], ev: Evidence): string {
  const out: string[] = ["# Review Queue", "", "> Generated by `npm run content:build`. Work from top to bottom. Approve with `npm run content:approve -- <id> --by <name>` (humans only).", ""];
  const all = results.flatMap((r) => r.issues.map((issue) => ({ id: r.id, issue })));

  const counts = { approved: 0, reviewed: 0, draft: 0, changed: 0 };
  results.forEach((r) => counts[r.status]++);
  out.push(`Concepts: ${results.length} · approved ${counts.approved} · reviewed ${counts.reviewed} · draft ${counts.draft} · changed since approval ${counts.changed}`, "");

  out.push("## 1. Blockers (build errors)", "");
  const errors = [...global.map((issue) => ({ id: "(global)", issue })), ...all.filter((x) => x.issue.level === "error")];
  out.push(...(errors.length ? issueRows(errors) : ["None."]), "");

  out.push("## 2. Changed since approval", "");
  const changed = results.filter((r) => r.status === "changed");
  out.push(...(changed.length ? changed.map((r) => `- \`${r.id}\`: re-review needed (${r.blockers.length ? r.blockers.join("; ") : "content or cited pages changed"})`) : ["None."]), "");

  out.push("## 3. Count conflicts", "");
  const conflicts = all.filter((x) => /count-mismatch/.test(x.issue.code));
  out.push(...(conflicts.length ? issueRows(conflicts) : ["None."]), "");

  out.push("## 4. Errata (answer-key errors in the CBLMs)", "");
  const suggested = results.flatMap((r) => r.suggestedErrata.map((s) => ({ ...s, concept: r.id })));
  const open = errata.filter((e) => e.status === "open");
  if (!suggested.length && !open.length) out.push("None.");
  for (const s of suggested) {
    const q = ev.questions.get(s.questionId) as Extract<EvQuestion, { kind: "selfcheck" }>;
    out.push(`- **Suspected** \`${s.questionId}\` (concept \`${s.concept}\`): "${esc(q.item.question)}". The answer key says "${esc(cut(q.item.answer ?? "", 100))}" (${pdfLink(ev, q.src, q.item.answerPage ?? q.item.questionPage)}). Add a confirmed or rejected entry to \`content/cbta/errata.json\`.`);
  }
  for (const e of open) out.push(`- **Open** \`${e.id}\`: ${esc(e.issue)} → proposed: ${esc(e.proposed)}`);
  out.push("");

  out.push("## 5. [CHECK] items", "");
  const checks = all.filter((x) => x.issue.level === "check");
  out.push(...(checks.length ? issueRows(checks) : ["None."]), "");

  out.push("## 6. Warnings (close quote matches, weak support, long verbatim sentences)", "");
  const warns = all.filter((x) => x.issue.level === "warn");
  out.push(...(warns.length ? issueRows(warns) : ["None."]), "");

  out.push("## 7. Awaiting review (★★★ first)", "");
  const drafts = results.filter((r) => r.status === "draft" || r.status === "reviewed")
    .sort((a, b) => b.stars - a.stars || b.score - a.score || a.id.localeCompare(b.id));
  if (!drafts.length) out.push("None.");
  else {
    out.push("| Concept | Stars | Score | Status | Ready to approve? |", "|---|---|---|---|---|");
    for (const r of drafts) out.push(`| \`${r.id}\` | ${starStr(r.stars)} | ${r.score} | ${r.status} | ${r.blockers.length ? `no: ${esc(cut(r.blockers.join("; "), 90))}` : "yes"} |`);
  }
  out.push("");
  return out.join("\n");
}

const COMMANDS: [string, RegExp][] = [
  ["differentiate", /\b(difference|differentiate|distinguish|compare|differ)\b/i],
  ["define", /^(define|what\s+(is|are)\b|what\s+do\s+you\s+(mean|understand)\s+by)/i],
  ["list", /^(list|write(\s+down)?|name|mention|state|give|identify|outline)\b/i],
  ["why", /^why\b/i],
  ["explain", /^(explain|describe|discuss|how)\b/i],
  ["who / when / which", /^(who|when|which|where)\b/i],
];

function commandOf(text: string): string {
  const t = text.trim();
  for (const [name, re] of COMMANDS) if (re.test(t)) return name;
  return "other";
}

const words = (s: string) => s.split(/\s+/).filter((w) => /\w/.test(w)).length;

export function renderPatternAnalysis(ev: Evidence, results: ConceptResult[]): string {
  const out: string[] = ["# Pattern Analysis", "", "> Generated by `npm run content:build` from the question papers and CBLM Self Checks. Do not edit by hand.", ""];
  const qs = [...ev.questions.values()];
  const papers = new Map<string, EvQuestion[]>();
  for (const q of qs) if (q.kind === "paper") (papers.get(q.src) ?? papers.set(q.src, []).get(q.src)!).push(q);

  out.push("## Paper structure", "", "| Paper | Class | MCQ | Matching | Short |", "|---|---|---|---|---|");
  for (const [, list] of [...papers].sort()) {
    const c = (t: string) => list.filter((q) => q.kind === "paper" && q.item.type === t).length;
    const first = list[0] as Extract<EvQuestion, { kind: "paper" }>;
    out.push(`| ${first.title} | ${first.paperClass} | ${c("mcq")} | ${c("matching")} | ${c("short")} |`);
  }
  out.push("", "**Mock exam blueprint:** the full papers all use **10 MCQ + 5 matching + 10 short** (25 questions). The Final Formative gives **1 hour** for this. No paper has viva questions, so viva practice is derived from short questions and definitions and labelled \"derived\". No paper states marks per question.", "");

  out.push("## Command words (short and self-check questions)", "");
  const written = qs.filter((q) => q.kind === "selfcheck" || q.item.type === "short");
  const freq = new Map<string, number>();
  for (const q of written) {
    const k = commandOf(q.item.question);
    freq.set(k, (freq.get(k) ?? 0) + 1);
  }
  out.push("| Command | Questions | Share |", "|---|---|---|");
  for (const [k, n] of [...freq].sort((a, b) => b[1] - a[1])) out.push(`| ${k} | ${n} | ${Math.round((n / written.length) * 100)}% |`);
  out.push("", `Based on ${written.length} written questions (${qs.filter((q) => q.kind === "selfcheck").length} from CBLM Self Checks, the rest from papers).`, "");

  const ans = written.map((q) => q.kind === "selfcheck" ? q.item.answer : q.item.answer).filter((a): a is string => !!a).map(words).sort((a, b) => a - b);
  if (ans.length) {
    const med = ans[Math.floor(ans.length / 2)];
    const p25 = ans[Math.floor(ans.length * 0.25)], p75 = ans[Math.floor(ans.length * 0.75)];
    out.push("## Typical answer length", "", `Model answers in the papers and answer keys have a median of **${med} words** (middle half: ${p25}–${p75} words, ${ans.length} answers). Concept cards aim for to-the-point answers inside this range.`, "");
  }

  out.push("## Priority formula", "", "```",
    "priority = highlight_weight + repeat_count_across_CBLMs + exam_pattern_frequency",
    "  highlight_weight          = 2 if highlighted, +1 if highlighted in ≥2 places",
    "  repeat_count_across_CBLMs = distinct CBLMs that mention the concept",
    "  exam_pattern_frequency    = 3 × official papers + 2 × formative/unit papers + 2 × self checks",
    "stars: ★★★ top 25% (or asked in an official paper) · ★★ next 40% · ★ rest · highlighted ≥ ★★",
    "```", "");

  out.push("## Concept ranking (authored concepts so far)", "");
  const ranked = results.filter((r) => r.concept).sort((a, b) => b.score - a.score || a.id.localeCompare(b.id));
  if (!ranked.length) out.push("No concepts authored yet.");
  else {
    out.push("| # | Concept | CBLM | Stars | Score | Highlight | Repeat | Exam | Why important |", "|---|---|---|---|---|---|---|---|---|");
    ranked.forEach((r, i) => out.push(`| ${i + 1} | ${esc(r.concept!.canonical_title)} | ${r.concept!.cblmPrimary} | ${starStr(r.stars)} | ${r.score} | ${r.breakdown.highlight} | ${r.breakdown.repeat} | ${r.breakdown.exam} | ${esc(r.importance.en)} |`));
  }
  out.push("");

  out.push("## Common traps (from authored cards)", "");
  const traps = ranked.flatMap((r) => r.concept!.traps.map((t) => `- **${esc(r.concept!.canonical_title)}**: ${esc(t.text)}`));
  out.push(...(traps.length ? traps : ["None yet."]), "");
  return out.join("\n");
}
