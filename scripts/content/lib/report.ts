// Markdown rendering for docs/plan/EXTRACTION_REPORT.md (generated; deterministic).

import type { CblmSummary, PaperSummary } from "../derive.ts";
import type { SelfCheckPair } from "./selfcheck.ts";
import type { PaperQuestion } from "./papers.ts";

const esc = (s: string) => s.replace(/\|/g, "\\|").replace(/\n+/g, " / ");
const cut = (s: string, n: number) => (s.length > n ? s.slice(0, n - 1) + "…" : s);

export function renderExtractionReport(
  cblms: CblmSummary[],
  papers: PaperSummary[],
  selfChecks: SelfCheckPair[],
  paperQs: PaperQuestion[],
): string {
  const sum = (f: (c: CblmSummary) => number) => cblms.reduce((s, c) => s + f(c), 0);
  const hl = sum((c) => c.annots.Highlight ?? 0);
  const ul = sum((c) => c.annots.Underline ?? 0);
  const out: string[] = [];

  out.push("# Extraction Report", "");
  out.push("> Generated by `npm run content:derive`. Do not edit by hand.", "");
  out.push("## Totals", "");
  out.push(`- CBLMs extracted: **${cblms.length} of 12**. CBLM 4 (Apply ICT to facilitate in training and assessment) has no PDF.`);
  out.push(`- Highlight annotations: **${hl}**; underline annotations: **${ul}**. Each one is inside a merged passage or listed as an empty marking; derive stops with an error if any is unaccounted for.`);
  out.push(`- Merged passages: **${sum((c) => c.passages)}**; markings over no text: **${sum((c) => c.emptyMarkup)}**; very short passages: **${sum((c) => c.shortPassages)}**.`);
  out.push(`- Teacher notes (FreeText/Ink/Caret): **${sum((c) => c.notes)}**; strikeouts/redactions (ignored, listed): **${sum((c) => c.strikeouts)}**.`);
  out.push(`- Self Check ↔ Answer Key pairs: **${selfChecks.length}**, of which **${selfChecks.filter((s) => s.flags.length).length}** are flagged for review.`);
  out.push(`- Paper questions: **${paperQs.length}** across ${papers.length} papers.`, "");

  out.push("## CBLMs", "");
  out.push("| CBLM | Pages | Highlight | Underline | Passages | Empty marks | Very short | Notes | Strike/Redact | Self-checks (flagged) | Pages to check |");
  out.push("|---|---|---|---|---|---|---|---|---|---|---|");
  for (const c of cblms) {
    out.push(`| ${c.cblm} | ${c.pages} | ${c.annots.Highlight ?? 0} | ${c.annots.Underline ?? 0} | ${c.passages} | ${c.emptyMarkup} | ${c.shortPassages} | ${c.notes} | ${c.strikeouts} | ${c.selfChecks} (${c.selfCheckFlagged}) | ${c.doubtPages.join(", ") || "—"} |`);
  }
  out.push("");
  out.push("**Pages to check** are pages with a marking over no extractable text, a very short passage, or very little text. Open the PDF page and compare it with the proof image in `content/cbta/.cache/proof/`.", "");

  out.push("### Detected structure", "");
  for (const c of cblms) {
    out.push(`- **CBLM ${c.cblm}**${c.parts > 1 ? ` (${c.parts} modules in one PDF)` : ""}: ${c.sections.join(" · ")}`);
  }
  out.push("");
  out.push("Section codes: `info` = Information Sheet, `selfcheck` = Self Check, `answerkey` = Answer Key, `job`/`spec` = Job/Specification Sheet, `m2-` = second module. In CBLM 8, module 2 (from page 40) is a blank CBLM template (\"Note to CBLM Developer\"), not real teaching content.", "");

  out.push("## Exam papers (question pattern)", "");
  out.push("| Paper | Class | MCQ | Matching | Short | Answers in paper | Flagged | Overrides |");
  out.push("|---|---|---|---|---|---|---|---|");
  for (const p of papers) {
    const a = p.answered;
    const ans = ["mcq", "matching", "short"].map((t) => `${a[t] ?? 0}/${p.counts[t] ?? 0}`).join(" · ");
    out.push(`| ${p.title} | ${p.paperClass} | ${p.counts.mcq ?? 0} | ${p.counts.matching ?? 0} | ${p.counts.short ?? 0} | ${ans} | ${p.flagged} | ${p.overridden} |`);
  }
  out.push("");
  const full = papers.filter((p) => p.counts.mcq && p.counts.matching && p.counts.short);
  const shapes = [...new Set(full.map((p) => `${p.counts.mcq} MCQ + ${p.counts.matching} matching + ${p.counts.short} short`))];
  out.push(`**Observed full-paper pattern:** ${shapes.join("; ") || "—"} (${full.length} papers: ${full.map((p) => p.title).join(", ")}).`);
  out.push("No paper contains viva questions, so viva practice will be derived from short questions and definitions and labelled as derived.", "");
  out.push("\"Answers in paper\" shows answered/total for MCQ · matching · short. A missing answer is never guessed: it is checked against the CBLM in the concept stage, or goes to REVIEW_QUEUE as `[CHECK]`.", "");

  const flaggedSc = selfChecks.filter((s) => s.flags.length);
  out.push("## Self Check items flagged for review", "");
  if (!flaggedSc.length) out.push("None.");
  else {
    out.push("| Id | Flag | Question | Answer key says | PDF page (Q / A) |");
    out.push("|---|---|---|---|---|");
    for (const s of flaggedSc) {
      out.push(`| ${s.id} | ${s.flags.join(", ")} | ${esc(cut(s.question, 80))} | ${esc(cut(s.answer ?? "—", 90))} | ${s.questionPage} / ${s.answerPage ?? "—"} |`);
    }
  }
  out.push("");
  out.push("`suspect-definition-mismatch` means the answer defines a different term from the one asked, as in the known OSH error where \"What is workplace hazard?\" is answered with the definition of a *workplace*. `restated-question-differs` means the question as restated in the answer key doesn't match the Self Check question, so the pairing needs a manual look.", "");

  const flaggedQ = paperQs.filter((q) => q.flags.some((f) => f !== "no-answer-in-paper" && f !== "overridden"));
  out.push("## Paper questions with parse warnings", "");
  if (!flaggedQ.length) out.push("None.");
  else for (const q of flaggedQ) out.push(`- \`${q.id}\` (${q.type}, PDF p.${q.page}): ${q.flags.join(", ")}: ${esc(cut(q.question, 90))}`);
  out.push("");
  return out.join("\n");
}

/** Coverage baseline before concepts exist; `content:build` (P1b) replaces this with real coverage. */
export function renderCoverageBaseline(cblms: CblmSummary[], selfChecks: number, paperQs: number): string {
  const out: string[] = [];
  out.push("# Coverage Report", "");
  out.push("> Baseline generated by `npm run content:derive`. No concepts have been written yet, so every item is uncovered. From P1b, `npm run content:build` owns this file and fails if any highlight stays uncovered.", "");
  out.push("| CBLM | Highlight annotations | Merged passages | Covered by a concept | Uncovered |");
  out.push("|---|---|---|---|---|");
  let hl = 0, ps = 0;
  for (const c of cblms) {
    hl += c.annots.Highlight ?? 0;
    ps += c.passages;
    out.push(`| ${c.cblm} | ${c.annots.Highlight ?? 0} | ${c.passages} | 0 | ${c.passages} |`);
  }
  out.push(`| **Total** | **${hl}** | **${ps}** | **0** | **${ps}** |`, "");
  out.push(`Questions waiting for a concept: ${selfChecks} Self Check pairs, ${paperQs} paper questions.`, "");
  out.push("CBLM 4 (Apply ICT to facilitate in training and assessment) has no PDF, so it has no highlights; its concepts will come from paper questions only.", "");
  return out.join("\n");
}
